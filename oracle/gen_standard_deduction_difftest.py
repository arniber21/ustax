#!/usr/bin/env python3
"""Generate catala/tests/oracle_standard_deduction.catala_en from oracle/facts.csv.

For each non-knocked-out scenario takes /filingStatus, /additionalStandardDeductionItems,
/employerIncomeSubtotal (inputs) and /standardDeduction (expected) from the Direct File engine.
Usage (from the repo root): python3 oracle/gen_standard_deduction_difftest.py
"""
import csv
import collections

FS = {"single": "Single", "marriedFilingJointly": "MarriedFilingJointly",
      "marriedFilingSeparately": "MarriedFilingSeparately",
      "headOfHousehold": "HeadOfHousehold", "qualifiedSurvivingSpouse": "QualifyingSurvivingSpouse"}
KO = {"1099r-box-2b-total-distribution", "ats-2-1099r", "ats-2-1099r-blank-taxable",
      "ats-2-1099r-nonzero-taxable"}
WANT = {"/filingStatus", "/additionalStandardDeductionItems", "/employerIncomeSubtotal",
        "/standardDeduction"}

d = collections.defaultdict(dict)
for r in csv.DictReader(open("oracle/facts.csv")):
    if r["path"] in WANT and r["scenario"] not in KO:
        d[r["scenario"]][r["path"]] = r["value"]


def money(v):
    return "$" + format(float(v), ",.2f")


cases = []
for s in sorted(d):
    x = d[s]
    cases.append((s, FS[x["/filingStatus"]], int(x["/additionalStandardDeductionItems"]),
                  money(x["/employerIncomeSubtotal"]), money(x["/standardDeduction"])))

HEAD = """# Differential test of Standard_deduction against the Direct File oracle

GENERATED by `oracle/gen_standard_deduction_difftest.py` from `oracle/facts.csv`; do not edit.
%d scenarios (the 161 oracle scenarios minus the 4 knocked out). Facts used:
`/filingStatus`, `/additionalStandardDeductionItems` and `/employerIncomeSubtotal` as inputs,
`/standardDeduction` as the expected value. The oracle does not export
`/treatFilersAsDependents`, so each case is run with the dependent flag off and on. A case
passes if the flag-off result equals the oracle, or the flag-on result does; `dependent_cases`
counts those that needed the flag on. The item count n is fed as n flags (blind, 65 for the
primary, then blind, 65 for the spouse), so the spouse-gating rules are exercised only for MFJ
and MFS (see `test_standard_deduction.catala_en` for the gating).

> Using Types
> Using Standard_deduction as S

```catala-metadata
declaration structure Case:
  data index content integer
  data fs content Types.FilingStatus
  data items content integer
  data earned content money
  data expected content money

declaration structure CaseResult:
  data index content integer
  data matches_normal content boolean
  data matches_dependent content boolean

declaration scope CheckCase:
  input c content Case
  normal scope S.StandardDeduction
  dep scope S.StandardDeduction
  output result content CaseResult
```

```catala
scope CheckCase:
  definition normal.filing_status equals c.fs
  definition dep.filing_status equals c.fs
  definition normal.treat_as_mfs equals c.fs = MarriedFilingSeparately
  definition dep.treat_as_mfs equals c.fs = MarriedFilingSeparately
  definition normal.primary_filer_is_blind equals c.items >= 1
  definition dep.primary_filer_is_blind equals c.items >= 1
  definition normal.primary_filer_age65_or_older equals c.items >= 2
  definition dep.primary_filer_age65_or_older equals c.items >= 2
  definition normal.secondary_filer_is_blind equals c.items >= 3
  definition dep.secondary_filer_is_blind equals c.items >= 3
  definition normal.secondary_filer_age65_or_older equals c.items >= 4
  definition dep.secondary_filer_age65_or_older equals c.items >= 4
  definition normal.is_widowed_in_tax_year equals false
  definition dep.is_widowed_in_tax_year equals false
  definition normal.mfj_deceased_spouse_reached_age65 equals false
  definition dep.mfj_deceased_spouse_reached_age65 equals false
  definition normal.mfs_spouse_65_or_older equals c.items >= 4
  definition dep.mfs_spouse_65_or_older equals c.items >= 4
  definition normal.mfs_spouse_provides_no_benefits equals false
  definition dep.mfs_spouse_provides_no_benefits equals false
  definition normal.treat_filers_as_dependents equals false
  definition dep.treat_filers_as_dependents equals true
  definition normal.employer_income_subtotal equals c.earned
  definition dep.employer_income_subtotal equals c.earned
  definition result equals CaseResult {
    -- index: c.index
    -- matches_normal: normal.standard_deduction = c.expected
    -- matches_dependent: dep.standard_deduction = c.expected
  }
```

```catala
#[test]
declaration scope OracleStandardDeduction:
  output ok condition
  output total content integer
  output matched content integer
  output dependent_cases content integer
  internal cases content list of Case
  internal results content list of CaseResult

scope OracleStandardDeduction:
  definition cases equals [
"""

TAIL = """
  ]
  definition results equals
    map each c among cases to (output of CheckCase with { -- c: c }).result
  definition total equals number of cases
  definition matched equals
    number of (list of r among results such that (r.matches_normal or r.matches_dependent))
  definition dependent_cases equals
    number of (list of r among results such that ((not r.matches_normal) and r.matches_dependent))
  rule ok under condition matched = total consequence fulfilled
  assertion matched = total
```
"""

body = ";\n".join(
    '    # %s\n    Case { -- index: %d -- fs: %s -- items: %d -- earned: %s -- expected: %s }'
    % (c[0], i, c[1], c[2], c[3], c[4]) for i, c in enumerate(cases))
open("catala/tests/oracle_standard_deduction.catala_en", "w").write(HEAD % len(cases) + body + TAIL)
print(len(cases), "cases")
