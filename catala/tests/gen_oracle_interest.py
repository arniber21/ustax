#!/usr/bin/env python3
"""Generate catala/tests/oracle_interest.catala_en from oracle/facts.csv.

One test scope per Direct File scenario. The scope feeds the scenario's
interest reports and the facts the Interest scope takes as inputs into
Interest.Interest, and asserts the three oracle values /interestIncome,
/taxExemptInterest and /requiresScheduleB, plus `not unsupported` (the oracle
holds no interest knockout facts; DF scenarios are supported returns).

Usage (from the repository root):
    python3 catala/tests/gen_oracle_interest.py > catala/tests/oracle_interest.catala_en
"""
import csv
import re
import sys
from collections import defaultdict
from decimal import Decimal

ROWS = defaultdict(dict)
with open("oracle/facts.csv", newline="") as f:
    for r in csv.DictReader(f):
        ROWS[r["scenario"]][r["path"]] = r["value"]

STATUS = {
    "single": "Single",
    "marriedFilingJointly": "MarriedFilingJointly",
    "marriedFilingSeparately": "MarriedFilingSeparately",
    "headOfHousehold": "HeadOfHousehold",
    "qualifiedSurvivingSpouse": "QualifyingSurvivingSpouse",
}


def money(s):
    d = Decimal(s) if s not in ("", None) else Decimal(0)
    cents = int((d * 100).to_integral_value())
    neg = cents < 0
    cents = abs(cents)
    out = "$%d.%02d" % (cents // 100, cents % 100)
    return "-" + out if neg else out


def boolean(s):
    return "true" if s == "true" else "false"


def report_fields(facts, rid):
    pre = "/interestReports/#%s/" % rid
    g = lambda name, d="0": facts.get(pre + name, d)
    filer_id = facts[pre + "filer"]
    primary = facts.get("/filers/#%s/isPrimaryFiler" % filer_id) == "true"
    return [
        ("filer", "Types.FilerRole.PrimaryFiler" if primary else "Types.FilerRole.SecondaryFiler"),
        ("has_1099", boolean(g("has1099", "false"))),
        ("no_1099_amount", money(g("no1099Amount"))),
        ("writable_1099_amount", money(g("writable1099Amount"))),
        ("writable_early_withdrawl_penalty_amount", money(g("writableEarlyWithdrawlPenaltyAmount"))),
        ("writable_interest_on_government_bonds", money(g("writableInterestOnGovernmentBonds"))),
        ("writable_tax_withheld", money(g("writableTaxWithheld"))),
        ("writable_foreign_tax_paid", money(g("writableForeignTaxPaid"))),
        ("writable_tax_exempt_interest", money(g("writableTaxExemptInterest"))),
        ("writable_specified_private_activity_bond_interest", money(g("writableSpecifiedPrivateActivityBondInterest"))),
        ("writable_market_discount", money(g("writableMarketDiscount"))),
        ("writable_bond_premium", money(g("writableBondPremium"))),
        ("writable_bond_premium_on_treasury_obligations", money(g("writableBondPremiumOnTreasuryObligations"))),
        ("writable_bond_premium_on_tax_exempt_bond", money(g("writableBondPremiumOnTaxExemptBond"))),
        ("state_is_different_state", boolean("true" if g("writableState", "") == "differentState" else "false")),
        ("writable_state_tax_withheld", money(g("writableStateTaxWithheld"))),
        ("facta_filing_required", boolean(g("factaFilingRequired", "false"))),
    ]


out = []
out.append("""# Interest module against the Direct File oracle (GENERATED)

Generated by `catala/tests/gen_oracle_interest.py` from `oracle/facts.csv`
(issue #6). Do not edit by hand; regenerate. One test scope per Direct File
backend scenario: the scenario's interest reports and its filing status, AGI,
foreign-account answers and `flowHasSeenDeductions` go in, and the oracle
values of `/interestIncome` (Form 1040 line 2b), `/taxExemptInterest` (line
2a) and `/requiresScheduleB` must come out. The oracle has no interest
knockout facts, so each scope asserts `not unsupported` instead.

> Using Interest
> Using Types
""")

n = 0
for scen in sorted(ROWS):
    facts = ROWS[scen]
    n += 1
    ids = [x for x in facts.get("/interestReports", "").split(";") if x]
    reports = []
    for rid in ids:
        fields = report_fields(facts, rid)
        body = "\n".join("          -- %s: %s" % kv for kv in fields)
        reports.append("        Interest.InterestReport {\n%s\n        }" % body)
    rlist = "[\n" + ";\n".join(reports) + " ]" if reports else "[]"
    foreign = (
        facts.get("/hasForeignAccounts") == "true"
        or facts.get("/isForeignTrustsGrantor") == "true"
        or facts.get("/hasForeignTrustsTransactions") == "true"
    )
    name = "OracleInterest%03d" % n
    out.append("""## Scenario `%s`

```catala
#[test]
declaration scope %s:
  output result content Interest.Interest
  output ok condition

scope %s:
  rule ok fulfilled
  definition result equals
    output of Interest.Interest with {
      -- interest_reports: %s
      -- has_foreign_accounts_or_trusts: %s
      -- filing_status: Types.FilingStatus.%s
      -- agi: %s
      -- flow_has_seen_deductions: %s
    }
  assertion result.interest_income = %s
  assertion result.tax_exempt_interest = %s
  assertion %sresult.requires_schedule_b
  assertion not result.unsupported
```
""" % (
        scen, name, name, rlist,
        boolean("true" if foreign else "false"),
        STATUS[facts["/filingStatus"]],
        money(facts["/agi"]),
        boolean(facts.get("/flowHasSeenDeductions", "false")),
        money(facts["/interestIncome"]),
        money(facts["/taxExemptInterest"]),
        "" if facts["/requiresScheduleB"] == "true" else "not ",
    ))

sys.stdout.write("\n".join(out))
sys.stderr.write("%d scenarios\n" % n)
