(* Spike: skeleton Catala backend plugin emitting Lean 4 from lcalc.
   Emits Lean type declarations (structures, enums) and, for scope bodies,
   a histogram of the lcalc node kinds a full translator would have to handle.
   Not a translator: a feasibility and sizing probe for option (b). *)

open Catala_utils
open Shared_ast

let rec lean_typ fmt (t : typ) =
  match Mark.remove t with
  | TLit TBool -> Format.pp_print_string fmt "Bool"
  | TLit TInt -> Format.pp_print_string fmt "Int"
  | TLit TRat -> Format.pp_print_string fmt "Rat"
  | TLit TMoney -> Format.pp_print_string fmt "Catala.Money"
  | TLit TUnit -> Format.pp_print_string fmt "Unit"
  | TLit TDate -> Format.pp_print_string fmt "Catala.Date"
  | TLit TDuration -> Format.pp_print_string fmt "Catala.Duration"
  | TLit TPos -> Format.pp_print_string fmt "Catala.CodeLocation"
  | TStruct s -> StructName.format fmt s
  | TEnum e -> EnumName.format fmt e
  | TArray t -> Format.fprintf fmt "(List %a)" lean_typ t
  | TOption t -> Format.fprintf fmt "(Option %a)" lean_typ t
  | TTuple ts ->
    Format.fprintf fmt "(%a)"
      (Format.pp_print_list ~pp_sep:(fun f () -> Format.pp_print_string f " × ") lean_typ)
      ts
  | TArrow (args, r) ->
    Format.fprintf fmt "(%a → %a)"
      (Format.pp_print_list ~pp_sep:(fun f () -> Format.pp_print_string f " → ") lean_typ)
      args lean_typ r
  | TDefault t -> lean_typ fmt t
  | _ -> Format.pp_print_string fmt "/- unsupported type -/ Unit"

let emit_types fmt (ctx : decl_ctx) =
  EnumName.Map.iter
    (fun name cons ->
      Format.fprintf fmt "@[<v 2>inductive %a where" EnumName.format name;
      EnumConstructor.Map.iter
        (fun c ty ->
          match Mark.remove ty with
          | TLit TUnit -> Format.fprintf fmt "@,| %a" EnumConstructor.format c
          | _ -> Format.fprintf fmt "@,| %a : %a → %a" EnumConstructor.format c lean_typ ty
                   EnumName.format name)
        cons;
      Format.fprintf fmt "@]@,@,")
    ctx.ctx_enums;
  StructName.Map.iter
    (fun name fields ->
      Format.fprintf fmt "@[<v 2>structure %a where" StructName.format name;
      StructField.Map.iter
        (fun f ty -> Format.fprintf fmt "@,%a : %a" StructField.format f lean_typ ty)
        fields;
      Format.fprintf fmt "@]@,@,")
    ctx.ctx_structs

let histogram : (string, int) Hashtbl.t = Hashtbl.create 17
let bump k = Hashtbl.replace histogram k (1 + Option.value ~default:0 (Hashtbl.find_opt histogram k))

let rec walk : type m. (lcalc, m) gexpr -> unit = fun e ->
  (match Mark.remove e with
   | EAppOp { op = (op, _); _ } -> bump ("op:" ^ Operator.name op)
   | EFatalError_pos _ -> bump "EFatalError"
   | EMatch _ -> bump "EMatch"
   | EIfThenElse _ -> bump "EIfThenElse"
   | EAbs _ -> bump "EAbs"
   | EApp _ -> bump "EApp"
   | EStruct _ -> bump "EStruct"
   | EInj _ -> bump "EInj"
   | ELit _ -> bump "ELit"
   | EVar _ -> bump "EVar"
   | EArray _ -> bump "EArray"
   | EExternal _ -> bump "EExternal"
   | _ -> bump "other");
  Expr.shallow_fold (fun e () -> walk e) e ()

let run includes stdlib output optimize check_invariants closure_conversion options =
  let prg, _type_ordering, _ =
    Driver.Passes.lcalc options ~includes ~stdlib ~optimize ~check_invariants
      ~autotest:false ~typed:Expr.typed ~closure_conversion ~keep_special_ops:false
      ~monomorphize_types:false ~split_threshold:None ~renaming:None ~lift_pos:None
  in
  Driver.Commands.get_output_format options ~ext:"lean" output
  @@ fun _file fmt ->
  Format.fprintf fmt "@[<v>/- generated by lean_spike plugin (types only) -/@,@,";
  emit_types fmt prg.decl_ctx;
  Scope.fold_exprs ~f:(fun () e _ty -> walk e) ~init:() prg.code_items;
  Format.fprintf fmt "/- lcalc node histogram:@,";
  Hashtbl.iter (fun k v -> Format.fprintf fmt "  %s: %d@," k v) histogram;
  Format.fprintf fmt "-/@]@."

let term =
  let open Cmdliner.Term in
  const run
  $ Cli.Flags.include_dirs $ Cli.Flags.stdlib_dir $ Cli.Flags.output
  $ Cli.Flags.optimize $ Cli.Flags.check_invariants $ Cli.Flags.closure_conversion

let () = Driver.Plugin.register "lean-spike" term ~doc:"Spike: Lean types + lcalc histogram"
