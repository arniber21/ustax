// Generates api/knockout-reasons.json from the Catala KnockoutReason enum and
// docs/knockout-inventory.md. Run: node api/scripts/gen-reasons.mjs
// Re-run when #37/#38 add reasons; `make api-check` fails if the file is stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const catala = readFileSync(join(root, 'catala/knockouts_income.catala_en'), 'utf8');
const inv = readFileSync(join(root, 'docs/knockout-inventory.md'), 'utf8');

const enumBody = catala.split('declaration enumeration KnockoutReason:')[1].split('```')[0];
const codes = [...enumBody.matchAll(/^\s*--\s*(\w+)\s*$/gm)].map((m) => m[1]);

const catOfModule = {
  filers: 'filers', interest: 'interest', unemployment: 'unemployment', formW2s: 'w2',
  form1099Rs: 'retirement', socialSecurity: 'social_security', estimatedPayments: 'estimated_payments',
  familyAndHousehold: 'household', dependentsBenefitSplit: 'household', taxCalculations: 'process',
  hsa: 'hsa', ptc: 'health_coverage', cdcc: 'credits', income: 'income', '(flow.xml)': 'process',
};
const rows = new Map(); // code -> {df_fact, category}
const pending = [];
for (const line of inv.split('\n')) {
  const c = line.split('|').map((s) => s.trim());
  if (c.length < 8 || !/^\d+$/.test(c[1])) continue;
  const mod = c[2];
  const fact = c[3].replace(/`/g, '').replace(/^Not /, '');
  let cat = catOfModule[mod] ?? 'other';
  if (fact === '/flowKnockoutUnsupportedState') cat = 'state';
  if (fact === '/isTooLateToFileOrResubmit') cat = 'process';
  if (fact === '/saversCreditKnockouts') cat = 'credits';
  const m = c[6].match(/\(reason `(\w+)`\)/);
  if (m) rows.set(m[1], { df_fact: fact, category: cat });
  else if (!/constant false|no knockout/.test(c[5])) {
    const name = fact.replace(/^\//, '').replace(/^\w/, (x) => x.toUpperCase());
    pending.push({ code: name, df_fact: fact, category: cat, pending: true });
  }
}
const human = (s) => s.replace(/([a-z0-9])([A-Z])/g, '$1 $2').replace(/^\w/, (x) => x.toUpperCase());
const reasons = codes.map((code) => {
  const r = rows.get(code) ?? {
    df_fact: null,
    category: /Hsa/.test(code) ? 'hsa' : /1099Misc|Pfd/.test(code) ? 'income' : /Cdcc|CombatPay/.test(code) ? 'credits'
      : /1095A/.test(code) ? 'health_coverage' : /FilingStatus|QualifyingChild/.test(code) ? 'household' : 'other',
  };
  return { code, category: r.category, df_fact: r.df_fact, message: human(code), pending: false };
});
for (const p of pending) reasons.push({ ...p, message: human(p.code) });
const out = {
  _comment:
    'Generated by api/scripts/gen-reasons.mjs. pending=true: not yet in the Catala KnockoutReason enum (#37); code is provisional.',
  categories: [...new Set(reasons.map((r) => r.category))].sort(),
  reasons,
};
const text = JSON.stringify(out, null, 2) + '\n';
const target = join(root, 'api/knockout-reasons.json');

// catala/api_reasons.catala_en: the reason -> category function of the API (issue #38; generated, never edit by hand).
// The top-level Calculator wraps a KnockoutReason in IncomeOrHsa or Household; the category is that of the inner reason.
const camel = (c) => c.split('_').map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join('');
const catOf = new Map(reasons.map((r) => [r.code, r.category]));
const inner = codes.map((c) => `    -- KI.KnockoutReason.${c}: ApiReasonCategory.${camel(catOf.get(c))}`).join('\n');
const wrapArm = (w) => `    -- Calc.CalculatorKnockout.${w} content r: (output of InnerCategoryOf with { -- reason: r }).category`;
const catalaText = `> Module Api_reasons

> Using Knockouts_income as KI
> Using Calculator as Calc

# API reason categories (issue #38). GENERATED by api/scripts/gen-reasons.mjs from catala/knockouts_income.catala_en
# and docs/knockout-inventory.md: do not edit by hand (make api-reasons).

The API groups every knockout reason into one of ${out.categories.length} categories for the frontend's copy screens
(\`api/knockout-reasons.json\`). The wire form of a category is the snake_case of the constructor.

\`\`\`catala-metadata
declaration enumeration ApiReasonCategory:
${out.categories.map((c) => `  -- ${camel(c)}`).join('\n')}

declaration scope InnerCategoryOf:
  input reason content KI.KnockoutReason
  output category content ApiReasonCategory

declaration scope ApiReasonCategoryOf:
  input reason content Calc.CalculatorKnockout
  output category content ApiReasonCategory
\`\`\`

\`\`\`catala
scope InnerCategoryOf:
  definition category equals
    match reason with pattern
${inner}

scope ApiReasonCategoryOf:
  definition category equals
    match reason with pattern
${wrapArm('IncomeOrHsa')}
${wrapArm('Household')}
\`\`\`
`;
const catalaTarget = join(root, 'catala/api_reasons.catala_en');
if (process.argv.includes('--check')) {
  let cur = '', curC = '';
  try { cur = readFileSync(target, 'utf8'); } catch {}
  try { curC = readFileSync(catalaTarget, 'utf8'); } catch {}
  if (cur !== text || curC !== catalaText) {
    console.error('api/knockout-reasons.json or catala/api_reasons.catala_en is stale: run node api/scripts/gen-reasons.mjs');
    process.exit(1);
  }
} else {
  writeFileSync(target, text);
  writeFileSync(catalaTarget, catalaText);
}
console.log(`${reasons.length} reasons, categories: ${out.categories.join(', ')}`);
