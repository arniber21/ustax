#!/usr/bin/env python3
"""Generate the two data-driven Catala tests of the Tax_rates module.

  catala/tests/test_tax_rates_table.catala_en   all rows of the printed Tax Table
  catala/tests/test_tax_rates_oracle.catala_en  Direct File engine values (oracle/facts.csv)

Run from the repository root: python3 scripts/gen_tax_rates_tests.py
"""
import csv, collections


def money(x):
    s = f"{x:.2f}"
    if s.endswith(".00"):
        s = s[:-3]
    whole, _, cents = s.partition(".")
    whole = f"{int(whole):,}"
    return "$" + whole + ("." + cents if cents else "")


HEADER = """> Using Tax_rates as T
> Using Types

```catala-metadata
declaration structure {name}:
{fields}
```
"""

STATUSES = [
    ("single", "Single"),
    ("mfj", "MarriedFilingJointly"),
    ("mfs", "MarriedFilingSeparately"),
    ("hoh", "HeadOfHousehold"),
]

# ---- Tax Table -------------------------------------------------------------
rows = list(csv.DictReader(open("sources/forms-instructions/derived-tax-table-2024.csv")))
assert len(rows) == 2060
lit = []
for r in rows:
    lo, hi = int(r["at_least"]), int(r["but_less_than"])
    cols = " ".join(f"-- {k}: {money(int(r[k]))}" for k, _ in STATUSES)
    lit.append(f"    TableRow {{ -- lo: {money(lo)} -- hi: {money(hi)} {cols} }}")
body = ";\n".join(lit)

checks = "\n    and ".join(
    f"""(output of T.TentativeTax with {{
      -- taxable_income: x -- filing_status: {c}
    }}).tentative_tax_from_taxable_income = r.{k}"""
    for k, c in STATUSES
)

open("catala/tests/test_tax_rates_table.catala_en", "w").write(
    """> Using Tax_rates as T
> Using Types

# Golden test: the printed 2024 Tax Table (generated, do not edit)

Generated by `scripts/gen_tax_rates_tests.py` from
`sources/forms-instructions/derived-tax-table-2024.csv` (2,060 rows, the Tax
Table of `sources/forms-instructions/i1040gi--2024.pdf` pp 64 to 75, columns
single, married filing jointly, married filing separately, head of
household). Each row `[lo, hi)` is checked at its lowest dollar `lo` and at
its highest cent `hi - $0.01`, for all four columns: 16,480 checks. Married
filing jointly stands for the qualifying surviving spouse column too (same
printed column); `test_tax_rates.catala_en` checks the two statuses agree.

```catala-metadata
declaration structure TableRow:
  data lo content money
  data hi content money
  data single content money
  data mfj content money
  data mfs content money
  data hoh content money
```

```catala
#[test]
declaration scope TestTaxTableGolden:
  output ok condition
  internal rows content list of TableRow
  internal failures content integer

scope TestTaxTableGolden:
  definition rows equals [
"""
    + body
    + """
  ]
  definition failures equals
    number of (list of r among rows such that
      not (for all x among [r.lo; r.hi - $0.01] we have
    """ + checks + """))
  rule ok under condition failures = 0 consequence fulfilled
  assertion failures = 0
```
"""
)

# ---- oracle ----------------------------------------------------------------
vals = collections.defaultdict(dict)
for r in csv.DictReader(open("oracle/facts.csv")):
    if r["path"] in ("/taxableIncome", "/tentativeTaxFromTaxableIncome", "/filingStatus", "/flowIsKnockedOut"):
        vals[r["scenario"]][r["path"]] = r["value"]
ctor = {
    "single": "Single",
    "marriedFilingJointly": "MarriedFilingJointly",
    "marriedFilingSeparately": "MarriedFilingSeparately",
    "headOfHousehold": "HeadOfHousehold",
    "qualifiedSurvivingSpouse": "QualifyingSurvivingSpouse",
}
lit, skipped = [], []
for s in sorted(vals):
    v = vals[s]
    if v.get("/flowIsKnockedOut") == "true":
        skipped.append(s)
        continue
    ti, tx = float(v["/taxableIncome"]), float(v["/tentativeTaxFromTaxableIncome"])
    lit.append(
        f'    # {s}\n    OracleCase {{ -- status: {ctor[v["/filingStatus"]]} '
        f"-- taxable_income: {money(ti)} -- expected_tax: {money(tx)} }}"
    )
print(f"oracle cases: {len(lit)}, knocked out (skipped): {skipped}")
open("catala/tests/test_tax_rates_oracle.catala_en", "w").write(
    f"""> Using Tax_rates as T
> Using Types

# Differential test: Direct File engine values (generated, do not edit)

Generated by `scripts/gen_tax_rates_tests.py` from `oracle/facts.csv`: for
each of the {len(lit)} scenarios that Direct File does not knock out
(`/flowIsKnockedOut` false), `/taxableIncome` and `/filingStatus` are the
inputs and `/tentativeTaxFromTaxableIncome` is the expected output. Skipped
because knocked out: {", ".join(skipped)}.

```catala-metadata
declaration structure OracleCase:
  data status content Types.FilingStatus
  data taxable_income content money
  data expected_tax content money
```

```catala
#[test]
declaration scope TestTentativeTaxOracle:
  output ok condition
  internal cases content list of OracleCase
  internal failures content integer

scope TestTentativeTaxOracle:
  definition cases equals [
"""
    + ";\n".join(lit)
    + """
  ]
  definition failures equals
    number of (list of c among cases such that
      (output of T.TentativeTax with {
         -- taxable_income: c.taxable_income -- filing_status: c.status
       }).tentative_tax_from_taxable_income != c.expected_tax)
  rule ok under condition failures = 0 consequence fulfilled
  assertion failures = 0
```
"""
)
