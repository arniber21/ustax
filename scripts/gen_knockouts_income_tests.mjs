function lit(prefix, file, struct, over = {}, indent = '    ') {
  const fs = fields(file, struct);
  for (const k of Object.keys(over)) if (!fs.some(([n]) => n === k)) throw new Error(`no field ${k} in ${struct}`);
  return `${prefix} {\n` + fs.map(([n, t]) => `${indent}  -- ${n}: ${over[n] ?? dflt(t)}`).join('\n') + `\n${indent}}`;
}

