function fields(file, struct) {
  const lines = readFileSync(root + file, 'utf8').split('\n');
  const i = lines.findIndex((l) => l.startsWith(`declaration structure ${struct}:`));
  const out = [];
  for (let j = i + 1; j < lines.length && !lines[j].startsWith('```'); j++) {
    const m = /^\s+data (\w+) content (.+)$/.exec(lines[j]);
    if (m) out.push([m[1], m[2].trim()]);
  }
  return out;
}
