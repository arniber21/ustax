#!/usr/bin/env python3
"""Generate the golden Catala test of the Eitc module.

  catala/tests/test_eitc_table_golden.catala_en

from sources/forms-instructions/derived-eic-table-2024.csv (derived from the
2024 EIC Table by scripts/derive_eic_table.py). Two checks:

  1. every printed row, all eight columns, at its lowest and highest whole
     dollar, with earned income = AGI (the printed credit; rows at or above the
     completed phaseout amount of a column are not checked there, the table
     prints "can't take the credit");
  2. 3,000 pseudo-random (earned income, AGI) pairs, expected value taken from
     the instructions' EIC Worksheet B procedure: look up earned income; if AGI
     differs and is at least the threshold, look up AGI too and take the
     smaller.

Run from the repository root: python3 scripts/gen_eitc_golden_tests.py
"""
import csv

CSV = "sources/forms-instructions/derived-eic-table-2024.csv"
OUT = "catala/tests/test_eitc_table_golden.catala_en"
COLS = ["s0", "s1", "s2", "s3", "mfj0", "mfj1", "mfj2", "mfj3"]
# Rev. Proc. 2023-34 section 3.06(1); the generator's own copy, used only to
# pick pairs and to find the lookup rule of Worksheet B. The Catala test uses
# the module's parameters.
THRESHOLD = {"s": [10330, 22720, 22720, 22720], "mfj": [17250, 29640, 29640, 29640]}
COMPLETED = {"s": [18591, 49084, 55768, 59899], "mfj": [25511, 56004, 62688, 66819]}


def money(x):
    return "-$" + f"{-x:,}" if x < 0 else "$" + f"{x:,}"


with open(CSV) as f:
    rows = list(csv.DictReader(line for line in f if not line.startswith("#")))
assert len(rows) == 1337
table = {int(r["at_least"]): r for r in rows}


def lookup(x, col):
    lo = 1 if x < 50 else (x // 50) * 50
    return int(table[lo][col])


# ---- part 1: rows ------------------------------------------------------------
row_lits = []
for r in rows:
    lo, hi = int(r["at_least"]), int(r["but_less_than"])
    cols = " ".join(f"-- {c}: {money(int(r[c]))}" for c in COLS)
    row_lits.append(f"    TableRow {{ -- lo: {money(lo)} -- hi: {money(hi)} {cols} }}")

# ---- part 2: pairs -----------------------------------------------------------
state = 20240601


def rnd(n):
    """Deterministic LCG (glibc constants); the generated file is reproducible."""
    global state
    state = (1103515245 * state + 12345) % (2 ** 31)
    return state % n


pair_lits = []
for _ in range(3000):
    k = rnd(4)
    kind = "mfj" if rnd(2) else "s"
    comp = COMPLETED[kind][k]
    thr = THRESHOLD[kind][k]
    ei = 1 + rnd(comp - 1)
    mode = rnd(4)
    if mode == 0:
        agi = ei
    elif mode == 1:
        agi = ei - rnd(ei)  # AGI below earned income (above 0)
        agi = max(agi, 0)
    else:
        agi = ei + rnd(25000)
    if agi >= comp:
        agi = comp - 1 - rnd(500)
    col = kind + str(k)
    exp = lookup(ei, col)
    if agi != ei and agi >= thr:
        exp = min(exp, lookup(agi, col))
    pair_lits.append(
        f"    Pair {{ -- ei: {money(ei)} -- agi: {money(agi)} -- mfj: {'true' if kind == 'mfj' else 'false'}"
        f" -- n: {k} -- expected: {money(exp)} }}")

body_rows = ";\n".join(row_lits)
body_pairs = ";\n".join(pair_lits)

checks = " and\n    ".join(
    f"(let t equals output of E.EitcTable with {{\n"
    f"      -- earned_income: x -- agi: x -- is_mfj: {'true' if c.startswith('mfj') else 'false'}"
    f" -- qualifying_children: {c[-1]} }} in\n"
    f"     x >= t.completed_phaseout or t.amount = r.{c})"
    for c in COLS)

text = f"""> Using Eitc as E

# Golden test: the printed 2024 EIC Table (generated, do not edit)

Generated by `scripts/gen_eitc_golden_tests.py` from
`sources/forms-instructions/derived-eic-table-2024.csv` (1,337 rows, the 2024
Earned Income Credit (EIC) Table of `sources/forms-instructions/i1040gi--2024.pdf`
pp 46 to 56, derived by `scripts/derive_eic_table.py`). Each row `[lo, hi)` is
checked at its lowest and highest whole dollar, earned income equal to AGI, for
all eight printed columns (single, head of household or qualifying surviving
spouse, and married filing jointly, each with 0, 1, 2, 3 or more children).
A column is skipped at an income at or above its completed phaseout amount
(the table prints "can't take the credit" in the footnote).

The second test runs 3,000 pseudo-random pairs of earned income and AGI against
the lookup rule of EIC Worksheet B (`i1040gi--2024.pdf` pp 44 to 45): look up the
earned income; if AGI differs from it and is at least the phaseout threshold,
look up AGI as well and take the smaller credit.

```catala-metadata
declaration structure TableRow:
  data lo content money
  data hi content money
  data s0 content money
  data s1 content money
  data s2 content money
  data s3 content money
  data mfj0 content money
  data mfj1 content money
  data mfj2 content money
  data mfj3 content money

declaration structure Pair:
  data ei content money
  data agi content money
  data mfj content boolean
  data n content integer
  data expected content money
```

```catala
#[test]
declaration scope TestEicTableGolden:
  output ok condition
  internal rows content list of TableRow
  internal failures content integer

scope TestEicTableGolden:
  definition rows equals [
{body_rows}
  ]
  definition failures equals
    number of (list of r among rows such that
      not (for all x among [r.lo; r.hi - $1] we have
    {checks}))
  rule ok under condition failures = 0 consequence fulfilled
  assertion failures = 0

#[test]
declaration scope TestEicWorksheetBGolden:
  output ok condition
  internal pairs content list of Pair
  internal failures content integer

scope TestEicWorksheetBGolden:
  definition pairs equals [
{body_pairs}
  ]
  definition failures equals
    number of (list of p among pairs such that
      not ((output of E.EitcTable with {{
              -- earned_income: p.ei -- agi: p.agi -- is_mfj: p.mfj
              -- qualifying_children: p.n }}).amount = p.expected))
  rule ok under condition failures = 0 consequence fulfilled
  assertion failures = 0
```
"""
open(OUT, "w").write(text)
print(f"wrote {OUT}: {len(rows)} rows, {len(pair_lits)} pairs")
