#!/usr/bin/env python3
"""Generate lean/UsTax/TaxRates/TaxTableData.lean from the printed Tax Table.

Input: sources/forms-instructions/derived-tax-table-2024.csv (2,062 rows of the
2024 Tax Table, i1040gi--2024.pdf pp 64 to 75; columns at_least,
but_less_than, single, mfj, mfs, hoh, whole dollars).
Output: one Lean list literal of the rows, used by the golden test
lean/UsTax/TaxRates/TaxTable.lean (each row checked at its lowest dollar and
its highest cent, four statuses: 16,496 checks).

Run from the repository root: python3 scripts/gen_lean_tax_table.py
Then rebuild: cd lean && lake build UsTax.TaxRates.TaxTable
"""
import csv

SRC = "sources/forms-instructions/derived-tax-table-2024.csv"
OUT = "lean/UsTax/TaxRates/TaxTableData.lean"

rows = list(csv.DictReader(open(SRC)))
assert len(rows) == 2062, len(rows)
cols = ["at_least", "but_less_than", "single", "mfj", "mfs", "hoh"]

lines = []
for r in rows:
    vals = [int(r[c]) for c in cols]
    assert vals[0] < vals[1] and all(v >= 0 for v in vals)
    lines.append("  ⟨" + ", ".join(str(v) for v in vals) + "⟩")

header = f"""/-!
# The printed 2024 Tax Table (generated, do not edit)

Generated by `scripts/gen_lean_tax_table.py` from
`{SRC}` ({len(rows):,} rows; Form 1040 instructions,
`sources/forms-instructions/i1040gi--2024.pdf` pp 64 to 75). Whole dollars.
Checked by `UsTax/TaxRates/TaxTable.lean`.
-/

namespace UsTax.TaxRates.TaxTable

/-- One printed row: taxable income at least `atLeast` but less than
`butLessThan`; the tax for single, married filing jointly (also qualifying
surviving spouse), married filing separately and head of household. -/
structure Row where
  /-- "At least": the bottom of the row (inclusive). -/
  atLeast : Int
  /-- "But less than": the top of the row (exclusive). -/
  butLessThan : Int
  /-- Tax for single filers. -/
  single : Int
  /-- Tax for married filing jointly (and qualifying surviving spouse). -/
  mfj : Int
  /-- Tax for married filing separately. -/
  mfs : Int
  /-- Tax for head of household. -/
  hoh : Int

"""

# Long list literals hit Lean's `maxRecDepth`, so the rows are split into
# chunks of CHUNK rows and concatenated.
CHUNK = 100
chunks = [lines[i:i + CHUNK] for i in range(0, len(lines), CHUNK)]
body = ""
for k, ch in enumerate(chunks):
    body += f"/-- Rows {k * CHUNK + 1} to {k * CHUNK + len(ch)}. -/\n"
    body += f"def rows{k} : List Row := [\n" + ",\n".join(ch) + "]\n\n"

footer = (
    "/-- All rows of the printed table, in order. -/\n"
    "def rows : List Row :=\n  "
    + " ++ ".join(f"rows{k}" for k in range(len(chunks)))
    + "\n\nend UsTax.TaxRates.TaxTable\n"
)

with open(OUT, "w") as f:
    f.write(header + body + footer)
print(f"wrote {OUT}: {len(rows)} rows")
