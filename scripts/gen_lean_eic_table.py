#!/usr/bin/env python3
"""Generate lean/UsTax/Eitc/EicTableData.lean from the printed 2024 EIC Table.

Inputs:
  sources/forms-instructions/derived-eic-table-2024.csv (1,337 rows of the 2024 EIC
    Table, i1040gi--2024.pdf pp 46 to 56; columns at_least, but_less_than, s0..s3,
    mfj0..mfj3, whole dollars);
  catala/tests/test_eitc_table_golden.catala_en (generated by
    scripts/gen_eitc_golden_tests.py): its 3,000 (earned income, AGI) pairs and the
    expected credit of each, from the EIC Worksheet B lookup rule. Reusing them keeps
    the Lean golden test on exactly the pairs the Catala golden test runs.
Output: list literals used by the golden test lean/UsTax/Eitc/EicTable.lean.

Run from the repository root: python3 scripts/gen_lean_eic_table.py
Then rebuild: cd lean && lake build UsTax.Eitc.EicTable
"""
import csv
import re

SRC = "sources/forms-instructions/derived-eic-table-2024.csv"
PAIRS_SRC = "catala/tests/test_eitc_table_golden.catala_en"
OUT = "lean/UsTax/Eitc/EicTableData.lean"
COLS = ["s0", "s1", "s2", "s3", "mfj0", "mfj1", "mfj2", "mfj3"]

with open(SRC) as f:
    rows = list(csv.DictReader(line for line in f if not line.startswith("#")))
assert len(rows) == 1337, len(rows)

pair_re = re.compile(
    r"Pair \{ -- ei: \$([\d,]+) -- agi: \$([\d,]+) -- mfj: (true|false) -- n: (\d) -- expected: \$([\d,]+) \}")
pairs = []
for line in open(PAIRS_SRC):
    m = pair_re.search(line)
    if m:
        ei, agi, mfj, n, exp = m.groups()
        pairs.append((int(ei.replace(",", "")), int(agi.replace(",", "")), mfj, int(n),
                      int(exp.replace(",", ""))))
assert len(pairs) == 3000, len(pairs)

row_lines = []
for r in rows:
    vals = [int(r["at_least"]), int(r["but_less_than"])] + [int(r[c]) for c in COLS]
    assert vals[0] < vals[1] and all(v >= 0 for v in vals)
    row_lines.append("  ⟨" + ", ".join(str(v) for v in vals) + "⟩")
pair_lines = [f"  ⟨{ei}, {agi}, {mfj}, {n}, {exp}⟩" for ei, agi, mfj, n, exp in pairs]

header = f"""/-!
# The printed 2024 EIC Table (generated, do not edit)

Generated by `scripts/gen_lean_eic_table.py` from
`{SRC}` ({len(rows):,} rows; Form 1040 instructions,
`sources/forms-instructions/i1040gi--2024.pdf` pp 46 to 56; derived, not an IRS file) and
the {len(pairs):,} (earned income, AGI) pairs of `{PAIRS_SRC}`. Whole dollars.
Checked by `UsTax/Eitc/EicTable.lean`.
-/

namespace UsTax.Eitc.EicTable

/-- One printed row: income at least `atLeast` but less than `butLessThan`; the credit for
single, head of household or qualifying surviving spouse (`s0` to `s3`: 0, 1, 2, 3 or more
children) and for married filing jointly (`mfj0` to `mfj3`). -/
structure Row where
  atLeast : Int
  butLessThan : Int
  s0 : Int
  s1 : Int
  s2 : Int
  s3 : Int
  mfj0 : Int
  mfj1 : Int
  mfj2 : Int
  mfj3 : Int

/-- One earned income / AGI pair with the credit EIC Worksheet B gives. -/
structure Pair where
  earnedIncome : Int
  agi : Int
  mfj : Bool
  children : Nat
  expected : Int

"""

CHUNK = 100


def chunked(name, ty, lines):
    chunks = [lines[i:i + CHUNK] for i in range(0, len(lines), CHUNK)]
    body = ""
    for k, ch in enumerate(chunks):
        body += f"def {name}{k} : List {ty} := [\n" + ",\n".join(ch) + "]\n\n"
    body += (f"/-- All of them, in order. -/\ndef {name} : List {ty} :=\n  "
             + " ++ ".join(f"{name}{k}" for k in range(len(chunks))) + "\n\n")
    return body


with open(OUT, "w") as f:
    f.write(header + chunked("rows", "Row", row_lines) + chunked("pairs", "Pair", pair_lines)
            + "end UsTax.Eitc.EicTable\n")
print(f"wrote {OUT}: {len(rows)} rows, {len(pairs)} pairs")
