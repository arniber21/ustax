#!/usr/bin/env python3
"""Generate lean/UsTax/Ptc/Table2Data.lean from the Catala Table 2 test.

Input: catala/tests/test_ptc_table2.catala_en, whose 255 `Row { -- income: $X -- percent: P
-- figure: F }` literals are every row of Table 2 ("Applicable Figure") of the Instructions for
Form 8962 (2024) (sources/forms-instructions/i8962--2024.pdf p 10), extracted from the PDF text,
plus the rows "less than 150" and "400 or more": a household income in whole dollars (single
filer, 48 states, poverty line $14,580), the Worksheet 2 percentage and the printed figure.
Reusing them keeps the Lean test on exactly the rows the Catala test runs.
Output: the list literal checked by lean/UsTax/Ptc/Table2.lean. Decimals become exact
fractions over 10,000 (the figure has at most four decimals; the percentage is whole).

Run from the repository root: python3 scripts/gen_lean_ptc_table2.py
Then rebuild: cd lean && lake build UsTax.Ptc.Table2
"""
import re
from decimal import Decimal

SRC = "catala/tests/test_ptc_table2.catala_en"
OUT = "lean/UsTax/Ptc/Table2Data.lean"

row_re = re.compile(
    r"Row \{ -- income: \$([\d,]+) -- percent: ([\d.]+) -- figure: ([\d.]+) \}")
rows = []
for line in open(SRC):
    m = row_re.search(line)
    if m:
        income, percent, figure = m.groups()
        p = Decimal(percent)
        f = Decimal(figure) * 10000
        assert p == p.to_integral_value() and f == f.to_integral_value(), line
        rows.append((int(income.replace(",", "")), int(p), int(f)))
assert len(rows) == 255, len(rows)

body = ",\n".join(f"  ⟨{i}, {p}, {f}⟩" for i, p, f in rows)
text = f"""/-!
# Form 8962 Table 2, every row (generated, do not edit)

Generated by `scripts/gen_lean_ptc_table2.py` from the {len(rows)} rows of
`{SRC}` (Table 2 "Applicable Figure", Instructions for Form 8962 (2024),
`sources/forms-instructions/i8962--2024.pdf` p 10, extracted from the PDF text; plus the rows
"less than 150" and "400 or more"). Checked by `UsTax/Ptc/Table2.lean`.
-/

namespace UsTax.Ptc.Table2

/-- One row: the smallest whole-dollar household income (single filer, 48 states, poverty line
$14,580) whose Worksheet 2 percentage is `percent`, and the printed figure in ten-thousandths
(`603` is 0.0603). -/
structure Row where
  incomeDollars : Int
  percent : Int
  figureTenThousandths : Int

/-- The {len(rows)} rows. -/
def rows : List Row := [
{body}]

end UsTax.Ptc.Table2
"""
with open(OUT, "w") as f:
    f.write(text)
print(f"wrote {OUT}: {len(rows)} rows")
