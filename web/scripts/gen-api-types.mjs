// Generates src/api/types.gen.ts from ../api/schema.json (json-schema-to-typescript).
//   npm run gen:api         regenerate
//   npm run gen:api:check   fail if the committed file is stale
import { compile } from 'json-schema-to-typescript';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const schema = JSON.parse(readFileSync(join(root, '../api/schema.json'), 'utf8'));
const out = join(root, 'src/api/types.gen.ts');

const ts = await compile(schema, 'ApiDocument', {
  bannerComment:
    '/* GENERATED by web/scripts/gen-api-types.mjs from api/schema.json. Do not edit; run `npm run gen:api`. */',
  additionalProperties: false,
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  format: false,
  cwd: join(root, '../api'),
});

if (process.argv.includes('--check')) {
  let cur = '';
  try {
    cur = readFileSync(out, 'utf8');
  } catch {
    /* missing */
  }
  if (cur !== ts) {
    console.error('src/api/types.gen.ts is stale: run `npm run gen:api` and commit.');
    process.exit(1);
  }
  console.log('types.gen.ts is up to date.');
} else {
  writeFileSync(out, ts);
  console.log('wrote src/api/types.gen.ts');
}
